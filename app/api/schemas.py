from typing import Optional, List,Dict, Any
from pydantic import BaseModel, Field, field_validator

class GatewayRequest(BaseModel):
    prompt: str = Field(..., description="The user's input prompt")
    user_id: str = Field(..., description="Identifier for the user making the request")
    max_tokens: Optional[int] = Field(default=500, ge=1, le=4096, description="Maximum tokens to generate")
    metadata: Optional[Dict[str, Any]] = Field(default=None, description="Optional caller metadata")

    @field_validator("prompt")
    @classmethod
    def validate_prompt_not_empty(cls, value:str)-> str:
        cleaned_value=value.strip()
        if not cleaned_value:
            raise ValueError("Prompt cannot be empty or contain only whitespace.")
        return cleaned_value
    
    @field_validator("user_id")
    @classmethod
    def validate_user_id_not_empty(cls, value: str)->str:
        cleaned_value=value.strip()
        if not cleaned_value:
            raise ValueError("user_id cannot be empty or contain only workspace")
        return cleaned_value
    
class GatewayResponse(BaseModel):
    response: str = Field(..., description="The text response generated by the LLM or retrieved from cache")
    model_used: str = Field(..., description="The exact model identifier used to fulfill the request")
    cache_hit: bool = Field(..., description="Indicates whether the response was served from cache")
    cost_usd: float = Field(..., ge=0.0, description="Total monetary cost of the transaction in USD")